// Generate CSS variables and a TypeScript module from design/tokens.json,
// the single source of colours, fonts, radii and layout values.
// Runs before dev, build, test and typecheck (see package.json).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensPath = resolve(here, "../../design/tokens.json");
const tokens = JSON.parse(readFileSync(tokensPath, "utf8"));

const kebab = (s) => s.replace(/_/g, "-");
const banner = "Generated by web/scripts/gen-tokens.mjs from design/tokens.json. Do not edit.";

const css = [`/* ${banner} */`, ":root {"];
for (const [k, v] of Object.entries(tokens.color)) css.push(`  --color-${kebab(k)}: ${v};`);
tokens.species_palette.forEach((v, i) => css.push(`  --species-${i + 1}: ${v};`));
tokens.heat_ramp.forEach((v, i) => css.push(`  --heat-${i}: ${v};`));
css.push(`  --font-sans: ${tokens.font.sans};`);
css.push(`  --font-mono: ${tokens.font.mono};`);
for (const [k, v] of Object.entries(tokens.radius)) css.push(`  --radius-${kebab(k)}: ${v}px;`);
css.push(`  --layout-max-width: ${tokens.layout.max_width}px;`);
css.push(`  --layout-page-padding-x: ${tokens.layout.page_padding_x}px;`);
css.push(`  --min-touch-target: ${tokens.layout.min_touch_target}px;`);
css.push("}", "");

const ts = `// ${banner}

export const color = ${JSON.stringify(tokens.color, null, 2)} as const;

/** Species colours, assigned by selection order (first selected = index 0). */
export const speciesPalette = ${JSON.stringify(tokens.species_palette)} as const;

export const heatRamp = ${JSON.stringify(tokens.heat_ramp)} as const;

export const sexColors = ${JSON.stringify(tokens.sex_colors, null, 2)} as const;

export const layout = ${JSON.stringify(tokens.layout, null, 2)} as const;
`;

const out = resolve(here, "../src/styles/tokens.css");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css.join("\n"));
writeFileSync(resolve(here, "../src/lib/tokens.ts"), ts);
console.log("tokens: wrote src/styles/tokens.css and src/lib/tokens.ts");
